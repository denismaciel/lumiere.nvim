        ['@markup.strong'] = { bold = util.style(opts.bold, true) },
        ['@markup.underline'] = { underline = true },
        ['@module'] = { fg = colors.text, bg = bg, italic = opts.italic },
        ['@module.builtin'] = { fg = colors.text, bg = bg, italic = opts.italic },
        ['@namespace.builtin'] = { link = '@variable.builtin' },
        ['@none'] = {},
        ['@number'] = { link = 'Number' },
        ['@number.float'] = { link = 'Float' },
        ['@operator'] = { link = 'Operator' },
        ['@property'] = { fg = colors.text, bg = bg },
        ['@punctuation'] = { fg = colors.punctuation, bg = bg },
        ['@punctuation.bracket'] = { fg = colors.punctuation, bg = bg },
        ['@punctuation.delimiter'] = { fg = colors.punctuation, bg = bg },
        ['@punctuation.special'] = { fg = colors.punctuation, bg = bg },
        ['@punctuation.special.markdown'] = { fg = colors.orange, bg = bg },
