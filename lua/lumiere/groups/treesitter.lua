        ['@string.regexp'] = { fg = colors.blue, bg = bg },
        ['@tag'] = { fg = colors.text, bg = bg, bold = opts.bold },
        ['@tag.attribute'] = { fg = colors.text, bg = bg, italic = opts.italic },
        ['@tag.delimiter'] = { fg = colors.punctuation, bg = bg },
        ['@type'] = { link = 'Type' },
        ['@type.builtin'] = { link = 'Type' },
        ['@type.definition'] = { link = 'Typedef' },
        ['@type.qualifier'] = { link = 'Keyword' },
