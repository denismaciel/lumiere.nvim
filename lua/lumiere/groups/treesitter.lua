local M = {}

M.get = function(colors, opts)
    local bg = opts.transparent and colors.none or colors.background
    local heading_bg = {
        util.blend(colors.blue_bg_soft, colors.background, 0.45),
        util.blend(colors.green_bg, colors.background, 0.25),
        util.blend(colors.yellow_bg, colors.background, 0.45),
        util.blend(colors.magenta_bg, colors.background, 0.25),
        util.blend(colors.orange_bg, colors.background, 0.22),
        util.blend(colors.background_inactive, colors.background, 0.55),
    }

    local groups = {
        ['@annotation'] = { link = 'PreProc' },
        ['@attribute'] = { link = 'PreProc' },
        ['@boolean'] = { link = 'Boolean' },
        ['@character'] = { link = 'Character' },
        ['@character.printf'] = { link = 'Special' },
        ['@character.special'] = { link = 'Special' },
        ['@comment'] = { link = 'Comment' },
        ['@comment.todo'] = { link = 'Todo' },
        ['@comment.note'] = { link = 'Todo' },
        ['@comment.warning'] = { link = 'WarningMsg' },
        ['@comment.error'] = { link = 'ErrorMsg' },
        ['@constant'] = { link = 'Constant' },
        ['@constant.builtin'] = { fg = colors.text, bg = bg, bold = opts.bold },
        ['@constant.macro'] = { link = 'Define' },
        ['@constructor'] = { link = 'Type' },
        ['@diff.delta'] = { link = 'DiffChange' },
        ['@diff.minus'] = { link = 'DiffDelete' },
        ['@diff.plus'] = { link = 'DiffAdd' },
        ['@function'] = { link = 'Function' },
        ['@function.builtin'] = { link = 'Function' },
        ['@function.call'] = { link = 'Function' },
        ['@function.macro'] = { link = 'Macro' },
        ['@function.method'] = { link = 'Function' },
        ['@function.method.call'] = { link = 'Function' },
        ['@keyword'] = { link = 'Keyword' },
        ['@keyword.conditional'] = { link = 'Keyword' },
        ['@keyword.coroutine'] = { link = 'Keyword' },
        ['@keyword.debug'] = { link = 'Debug' },
        ['@keyword.directive'] = { link = 'PreProc' },
        ['@keyword.directive.define'] = { link = 'Define' },
        ['@keyword.exception'] = { fg = colors.red, bg = bg, bold = opts.bold },
        ['@keyword.function'] = { link = 'Keyword' },
        ['@keyword.import'] = { link = 'Keyword' },
        ['@keyword.operator'] = { link = 'Operator' },
        ['@keyword.repeat'] = { link = 'Keyword' },
        ['@keyword.return'] = { link = 'Keyword' },
        ['@keyword.storage'] = { link = 'StorageClass' },
        ['@label'] = { link = 'Label' },
        ['@markup'] = {},
        ['@markup.heading'] = { link = 'Title' },
        ['@markup.italic'] = { italic = util.style(opts.italic, true) },
        ['@markup.link'] = { fg = colors.blue, underline = true },
        ['@markup.link.label'] = { link = 'Special' },
        ['@markup.link.label.symbol'] = { link = 'Identifier' },
        ['@markup.link.url'] = { link = 'Underlined' },
        ['@markup.list'] = { fg = colors.blue, bg = bg },
        ['@markup.list.checked'] = { fg = colors.green, bg = bg },
        ['@markup.list.markdown'] = { fg = colors.orange, bg = bg, bold = opts.bold },
        ['@markup.list.unchecked'] = { fg = colors.blue, bg = bg },
        ['@markup.math'] = { link = 'Special' },
        ['@markup.raw'] = { bg = colors.surface_raised },
        ['@markup.raw.block'] = { bg = colors.surface_raised },
        ['@markup.raw.block.markdown'] = { bg = colors.surface_raised },
        ['@markup.raw.markdown_inline'] = { fg = colors.text, bg = colors.surface_raised },
