        ['@variable.builtin'] = { fg = colors.text, bg = bg, italic = opts.italic },
        ['@variable.member'] = { fg = colors.text, bg = bg },
        ['@variable.parameter'] = { fg = colors.text, bg = bg, italic = opts.italic },
        ['@variable.parameter.builtin'] = { fg = colors.text_muted, bg = bg, italic = opts.italic },
    }

    for level, level_bg in ipairs(heading_bg) do
        groups['@markup.heading.' .. level .. '.markdown'] = {
            fg = colors.text,
            bg = level_bg,
            bold = opts.bold,
        }
    end

    return groups
end

return M
